import * as path from 'path';

export type CviResourceCategory = 'memory' | 'ui' | 'file' | 'thread' | 'communication' | 'other';

export interface CviResourceItem {
  id: string; // Hex address (e.g. 0x0000021A4B0) or Handle ID
  category: CviResourceCategory;
  typeLabel: string; // e.g. "Dynamic Memory", "Panel Handle", "File Handle"
  sizeBytes?: number;
  details?: string; // e.g. "MainPanel", "sample.dat", etc.
  sourceFile?: string;
  lineNumber?: number;
  callStack?: string[];
  isLeaked?: boolean;
  timestamp?: string;
}

export interface CviResourceSnapshot {
  sessionId?: string;
  timestamp: Date;
  isActiveSession: boolean;
  isCleanExit?: boolean;
  totalBytes: number;
  items: CviResourceItem[];
  summary: {
    totalCount: number;
    memoryCount: number;
    uiCount: number;
    fileCount: number;
    threadCount: number;
    communicationCount: number;
    otherCount: number;
  };
}

export function formatBytes(bytes: number | undefined): string {
  if (bytes === undefined || isNaN(bytes)) {
    return '';
  }
  if (bytes < 1024) {
    return `${bytes} B`;
  }
  if (bytes < 1024 * 1024) {
    return `${(bytes / 1024).toFixed(1)} KB`;
  }
  return `${(bytes / (1024 * 1024)).toFixed(2)} MB`;
}

/**
 * Parses raw resource dump text generated by CVI runtime (__CVI_Resource_DumpToFile)
 * or diagnostic tracking hooks into a structured snapshot.
 */
export function parseResourceDump(content: string, workspaceRoot?: string, defaultSourceFile?: string): CviResourceSnapshot {
  const items: CviResourceItem[] = [];
  const lines = content.split(/\r?\n/);

  let currentItem: Partial<CviResourceItem> | null = null;
  let currentCallStack: string[] = [];

  const finalizeCurrentItem = () => {
    if (currentItem && currentItem.id) {
      if (currentCallStack.length > 0) {
        currentItem.callStack = [...currentCallStack];
      }
      if (!currentItem.sourceFile && defaultSourceFile && currentItem.lineNumber) {
        currentItem.sourceFile = defaultSourceFile;
      }
      if (!currentItem.category) {
        currentItem.category = categorizeItem(currentItem.typeLabel || '', currentItem.details || '');
      }
      items.push(currentItem as CviResourceItem);
    }
    currentItem = null;
    currentCallStack = [];
  };

  const cviHeaderRegex = /^(0x[0-9a-fA-F]+)\s+(\d+)\s+\(([^)]+)\)\s*(.*)$/;
  const cviFrameRegex = /^\s*(\d+):\s*(0x[0-9a-fA-F]+):(\d+)\.(\d+)-(\d+)\.(\d+)\s*\((0x[0-9a-fA-F]+)\)/;

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#') || line.startsWith('---') || line.startsWith('===')) {
      continue;
    }

    // Format 1: Native CVI runtime dump format
    // e.g.: 0x0000000000645438 22180 (User interface) Panel 1 "Untitled Panel" from resource PANEL in "Demo Antigravity.uir"
    // e.g.: 0x0000000004786B30 22180 (Memory) Block 0x0000000004786B30 of 65 bytes
    const cviHeaderMatch = line.match(cviHeaderRegex);
    if (cviHeaderMatch) {
      finalizeCurrentItem();
      const addr = cviHeaderMatch[1];
      const rawCat = cviHeaderMatch[3].toLowerCase();
      const desc = cviHeaderMatch[4].trim();

      let category: CviResourceCategory = 'other';
      let typeLabel = desc;
      let sizeBytes = 0;
      let details = desc;
      let itemId = addr;

      if (rawCat.includes('user interface') || rawCat.includes('ui')) {
        category = 'ui';
        typeLabel = 'Panel';
        const panelMatch = desc.match(/^(Panel\s+\d+)\s*(.*)$/i);
        if (panelMatch) {
          itemId = panelMatch[1];
          details = panelMatch[2] || desc;
        }
      } else if (rawCat.includes('memory')) {
        category = 'memory';
        typeLabel = 'Dynamic Memory';
        const blkMatch = desc.match(/^Block\s+(0x[0-9a-fA-F]+)\s+of\s+(\d+)\s+bytes/i);
        if (blkMatch) {
          itemId = blkMatch[1];
          sizeBytes = parseInt(blkMatch[2], 10);
          details = `${sizeBytes} bytes`;
        } else {
          const szMatch = desc.match(/(\d+)\s*bytes?/i);
          if (szMatch) {
            sizeBytes = parseInt(szMatch[1], 10);
          }
        }
      } else if (rawCat.includes('file')) {
        category = 'file';
        typeLabel = 'File Handle';
      } else if (rawCat.includes('thread') || rawCat.includes('lock')) {
        category = 'thread';
        typeLabel = 'Thread / Lock';
      } else if (rawCat.includes('comm') || rawCat.includes('socket')) {
        category = 'communication';
        typeLabel = 'Communication';
      }

      currentItem = {
        id: itemId,
        category,
        typeLabel,
        sizeBytes,
        details
      };
      continue;
    }

    // Format 1 stack frame: e.g. "    0: 0x0000000000669EBF:50.1-50.67 (0x0000000000400000)"
    const cviFrameMatch = rawLine.match(cviFrameRegex);
    if (cviFrameMatch && currentItem) {
      const fIdx = parseInt(cviFrameMatch[1], 10);
      const fIp = cviFrameMatch[2];
      const lineNum = parseInt(cviFrameMatch[3], 10);
      const colS = parseInt(cviFrameMatch[4], 10);
      const lineE = parseInt(cviFrameMatch[5], 10);
      const colE = parseInt(cviFrameMatch[6], 10);

      if (!currentItem.lineNumber) {
        currentItem.lineNumber = lineNum;
      }

      currentCallStack.push(`#${fIdx} line ${lineNum}:${colS}-${lineE}:${colE} (${fIp})`);
      continue;
    }

    // Format 2: Generic / fallback format: "0x1234: size=1024, at main.c:42 [malloc]"
    const standardMatch = line.match(/^(?:Resource\s+)?(0x[0-9a-fA-F]+|[A-Za-z0-9_]+(?:\s*\[\d+\])?)\s*[:\-]\s*(.*)$/);
    if (standardMatch) {
      finalizeCurrentItem();
      const id = standardMatch[1].trim();
      const rest = standardMatch[2].trim();

      currentItem = {
        id,
        category: 'other',
        typeLabel: id.startsWith('0x') ? 'Dynamic Memory' : 'Resource'
      };

      const sizeMatch = rest.match(/(?:size\s*[=:]\s*|(\d+)\s*bytes?)/i);
      if (sizeMatch) {
        const num = sizeMatch[1] ? parseInt(sizeMatch[1], 10) : parseInt(rest.slice(sizeMatch.index!).replace(/[^0-9]/g, ''), 10);
        if (!isNaN(num)) {
          currentItem.sizeBytes = num;
        }
      }

      const locMatch = rest.match(/([a-zA-Z0-9_\-\.\/\\]+\.[cChHpP]+)(?::(\d+))?/);
      if (locMatch) {
        let filePath = locMatch[1];
        if (workspaceRoot && !path.isAbsolute(filePath)) {
          filePath = path.join(workspaceRoot, filePath);
        }
        currentItem.sourceFile = filePath;
        if (locMatch[2]) {
          currentItem.lineNumber = parseInt(locMatch[2], 10);
        }
      }

      const detailsMatch = rest.match(/\[(.*?)\]|\((.*?)\)/);
      if (detailsMatch) {
        currentItem.details = detailsMatch[1] || detailsMatch[2];
        if (currentItem.details) {
          currentItem.typeLabel = currentItem.details;
        }
      }

      currentItem.category = categorizeItem(currentItem.typeLabel || '', currentItem.details || '');
      continue;
    }

    // Generic stack frame line, e.g.: "  at main() main.c:42" or "  #0 0x1234 in func() at file.c:10"
    if (currentItem && (rawLine.startsWith('   ') || rawLine.startsWith('\t') || rawLine.trim().startsWith('#') || rawLine.trim().startsWith('at '))) {
      currentCallStack.push(rawLine.trim());

      if (!currentItem.sourceFile) {
        const frameLocMatch = line.match(/([a-zA-Z0-9_\-\.\/\\]+\.[cChHpP]+)(?::(\d+))?/);
        if (frameLocMatch) {
          let filePath = frameLocMatch[1];
          if (workspaceRoot && !path.isAbsolute(filePath)) {
            filePath = path.join(workspaceRoot, filePath);
          }
          currentItem.sourceFile = filePath;
          if (frameLocMatch[2]) {
            currentItem.lineNumber = parseInt(frameLocMatch[2], 10);
          }
        }
      }
    }
  }

  finalizeCurrentItem();

  let totalBytes = 0;
  let memoryCount = 0;
  let uiCount = 0;
  let fileCount = 0;
  let threadCount = 0;
  let communicationCount = 0;
  let otherCount = 0;

  for (const item of items) {
    if (item.sizeBytes) {
      totalBytes += item.sizeBytes;
    }
    switch (item.category) {
      case 'memory': memoryCount++; break;
      case 'ui': uiCount++; break;
      case 'file': fileCount++; break;
      case 'thread': threadCount++; break;
      case 'communication': communicationCount++; break;
      default: otherCount++; break;
    }
  }

  return {
    timestamp: new Date(),
    isActiveSession: true,
    totalBytes,
    items,
    summary: {
      totalCount: items.length,
      memoryCount,
      uiCount,
      fileCount,
      threadCount,
      communicationCount,
      otherCount
    }
  };
}

function categorizeItem(typeLabel: string, details: string): CviResourceCategory {
  const combined = `${typeLabel} ${details}`.toLowerCase();
  if (/panel|ctrl|control|menu|bitmap|canvas|uir|timer/.test(combined)) {
    return 'ui';
  }
  if (/file|handle|stream|fp|disk/.test(combined)) {
    return 'file';
  }
  if (/thread|pool|mutex|lock|semaphore|event/.test(combined)) {
    return 'thread';
  }
  if (/tcp|udp|socket|rs232|com\d|visa|daq/.test(combined)) {
    return 'communication';
  }
  if (/memory|malloc|calloc|realloc|heap|byte|buffer|0x/.test(combined)) {
    return 'memory';
  }
  return 'other';
}
